const slug = title => title.toLowerCase().replace(/[^a-z0-9]+/g,'-').replace(/^-|-$/g,'');
export function entries(text, parentId, originalPrompts=[]) {
  return text.trim().split('\n').map(line=>{
    const [title,blurb,question]=line.split('|');
    const id=`${parentId}--${slug(title)}`;
    return {id,title,blurb,children:[],prompts:question==='='?originalPrompts:[{id:`${id}-q`,question,type:'reflection',suggestedThinkTime:30,suggestedSpeakTime:120}],related:[]};
  });
}

export function enrichDomains(domains) {
  const visit=item=>{
    const additions=topicAdditions[item.id];
    const children=[...(item.children||[]),...(domainAdditions[item.id]?entries(domainAdditions[item.id],item.id):[]),...(additions?entries(additions,item.id,item.prompts):[])].map(visit);
    return {...item,children,prompts:additions?.split('\n').some(line=>line.endsWith('|='))?[]:item.prompts};
  };
  return domains.map(visit);
}
